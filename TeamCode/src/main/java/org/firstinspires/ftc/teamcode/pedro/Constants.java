package org.firstinspires.ftc.teamcode.pedro;

import com.pedropathing.algorithm.Foresight;
import com.pedropathing.algorithm.ForesightConfig;
import com.pedropathing.controllers.Controller;
import com.pedropathing.follower.Follower;
import com.pedropathing.math.Matrix;
import com.pedropathing.math.Vector2D;
import com.pedropathing.revhub.drivetrains.Mecanum;
import com.pedropathing.revhub.drivetrains.MecanumConfig;
import com.pedropathing.revhub.localizers.PinpointConfig;
import com.pedropathing.revhub.localizers.PinpointLocalizer;
import com.qualcomm.hardware.gobilda.GoBildaPinpointDriver;
import com.qualcomm.robotcore.hardware.DcMotorSimple;
import com.qualcomm.robotcore.hardware.HardwareMap;

import org.firstinspires.ftc.robotcore.external.navigation.DistanceUnit;
import org.firstinspires.ftc.teamcode.robot.HardwareNames;

/**
 * The robot's Pedro Pathing settings.
 *
 * The values come from AutoTune, run in this order:
 * Mecanum Tuner -> Pinpoint Tuner -> Foresight Tuner -> Tests.
 * Each tuner prints the Java code to paste here.
 */
public class Constants {
    public static MecanumConfig drivetrainConfig = new MecanumConfig(
            c -> {
                c.frontLeftName.set(HardwareNames.FRONT_LEFT);
                c.frontRightName.set(HardwareNames.FRONT_RIGHT);
                c.backLeftName.set(HardwareNames.BACK_LEFT);
                c.backRightName.set(HardwareNames.BACK_RIGHT);
                c.frontLeftDirection.set(DcMotorSimple.Direction.FORWARD);
                c.frontRightDirection.set(DcMotorSimple.Direction.REVERSE);
                c.backLeftDirection.set(DcMotorSimple.Direction.FORWARD);
                c.backRightDirection.set(DcMotorSimple.Direction.FORWARD);
                c.manualBrakeMode.set(true);
            }
    );

    public static PinpointConfig localizerConfig = new PinpointConfig(
            c -> {
                c.name.set(HardwareNames.PINPOINT);
                c.podType.set(GoBildaPinpointDriver.GoBildaOdometryPods.goBILDA_4_BAR_POD);
                c.xPodOffset.set(0.7652253428782065);
                c.yPodOffset.set(-4.43379319558932);
                c.xPodDirection.set(GoBildaPinpointDriver.EncoderDirection.FORWARD);
                c.yPodDirection.set(GoBildaPinpointDriver.EncoderDirection.REVERSED);
                c.globalDistanceUnit.set(DistanceUnit.INCH);
                c.offsetUnits.set(DistanceUnit.INCH);
            }
    );

    // Generated by the Foresight Tuner
public static ForesightConfig foresightConfig = new ForesightConfig(
            c -> {
                Controller primaryTranslationalForward = Controller.proportional(0.5313386442141714);
                Controller secondaryTranslationalForward = Controller.proportional(0.1963154314070814);
                Controller primaryTranslationalLateral = Controller.proportional(1.2250187948210567);
                Controller secondaryTranslationalLateral = Controller.proportional(0.4526117115813286);

                c.forwardTranslational.set(Controller.piecewise(secondaryTranslationalForward).put(2.5, primaryTranslationalForward));
                c.strafeTranslational.set(Controller.piecewise(secondaryTranslationalLateral).put(2.5, primaryTranslationalLateral));

                c.coast.set(Controller.proportionalFeedforward(0.013867946603230782));
                c.brake.set(Controller.proportionalFeedforward(0.011787754612746164));

                c.headingFeedback.set(Controller.proportional(9.48422245624233));
                c.headingBrakeCoefficients.set(Vector2D.cartesian(0.06356267621564583, 0.004107739726673471));

                c.linearBrakeCoefficients.set(Matrix.diag(0.08473657021187349, 0.06558270557283713));
                c.quadraticBrakeCoefficients.set(Matrix.diag(0.00220939989519344, 0.0017029151968126477));

                c.maxAchievableForwardVelocity.set(68.72115488666158);
                c.maxAchievableStrafeVelocity.set(47.923987334433704);
                c.naturalForwardDeceleration.set(31.127912704235328);
                c.naturalStrafeDeceleration.set(78.67646937251284);
            }
    );
    
    public static Follower create(HardwareMap h) {
        return new Follower(
                new PinpointLocalizer(h, localizerConfig),
                new Mecanum(h, drivetrainConfig),
                new Foresight(foresightConfig)
        );
    }
}
